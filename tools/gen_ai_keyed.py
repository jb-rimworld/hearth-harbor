#!/usr/bin/env python3
"""Generates Common/Languages/English/Keyed/HH_Ai.xml from every AiT.T("Key", "English text") literal in Source/Hearth/Ai
plus the stock review lines of Source/Hearth.Core/Pure/Ai/AiRelay.cs (keys HH.Ai.Review.Fallback.<stars>.<n>).
Run: python3 tools/gen_ai_keyed.py   (keys become HH.Ai.<Key>; the C# fallback and the Keyed file can never drift)."""
import re, sys
from pathlib import Path
from xml.sax.saxutils import escape
R = Path(__file__).resolve().parent.parent
pat = re.compile(r'AiT\.T\(\s*"((?:[^"\\]|\\.)*)"\s*,\s*"((?:[^"\\]|\\.)*)"')
keys = {}
def un(s): return s.replace('\\n', '\n').replace('\\"', '"').replace('\\\\', '\\')
for f in sorted((R / "Source" / "Hearth" / "Ai").rglob("*.cs")):
    if f.name in ("AiT.cs", "AiTests.cs"): continue
    for m in pat.finditer(f.read_text(encoding="utf-8")):
        k, v = m.group(1), un(m.group(2))
        if k in keys and keys[k] != v: print("WARNING duplicate key with different text:", k, file=sys.stderr)
        keys.setdefault(k, v)
keys.setdefault("Tab.Ottoline", "Ask Ottoline")
# settings of the module: HSettings.Bool(M, "Category", "ai.key", default, "Label", "Description"...)
settings = {}
spat = re.compile(r'HSettings\.\w+\(M,\s*"[^"]*",\s*"(ai\.[A-Za-z.]+)",[^"]*"((?:[^"\\]|\\.)*)"(?:,\s*"((?:[^"\\]|\\.)*)")?')
for m in spat.finditer((R / "Source" / "Hearth" / "Ai" / "AiModule.cs").read_text(encoding="utf-8")):
    settings[m.group(1)] = (un(m.group(2)), un(m.group(3) or ""))
# stock review lines: rows of the ReviewLines table, row 0 is null, rows 1..5 are the stars
src = (R / "Source" / "Hearth.Core" / "Pure" / "Ai" / "AiRelay.cs").read_text(encoding="utf-8")
block = src[src.index("ReviewLines ="):]
block = block[:block.index("};")]
rows = [m.group(1) for m in re.finditer(r'new\[\]\s*\{(.*?)\}\s*,', block, re.S)]
for stars, row in enumerate(rows, start=1):
    for i, m in enumerate(re.finditer(r'"((?:[^"\\]|\\.)*)"', row)):
        keys[f"Review.Fallback.{stars}.{i}"] = un(m.group(1))
out = ['<?xml version="1.0" encoding="utf-8"?>', "<LanguageData>", "  <!-- generated by tools/gen_ai_keyed.py from the AiT.T(...) calls in Source/Hearth/Ai; do not edit by hand -->"]
for k in sorted(keys):
    out.append(f"  <HH.Ai.{k}>{escape(keys[k])}</HH.Ai.{k}>")
for k in sorted(settings):
    out.append(f"  <HH.Setting.{k}>{escape(settings[k][0])}</HH.Setting.{k}>")
    if settings[k][1]: out.append(f"  <HH.Setting.{k}.Desc>{escape(settings[k][1])}</HH.Setting.{k}.Desc>")
out.append("</LanguageData>")
p = R / "Common" / "Languages" / "English" / "Keyed" / "HH_Ai.xml"
p.write_text("\n".join(out) + "\n", encoding="utf-8")
print(f"{len(keys)} texts + {len(settings)} settings -> {p.relative_to(R)}")
