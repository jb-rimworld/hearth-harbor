#!/usr/bin/env python3
"""Writes Common/Languages/English/Keyed/HH_Settings.xml: translation keys for every setting label/description, setting
category and enum value that no other English Keyed file defines yet (so they can be translated like everything else).

    tools/run_test.sh core.settingsdump <label>     # dumps settings_dump.json from the running game
    python3 tools/i18n/settings_keyed.py [dump.json]
"""
import json, re, sys
import xml.etree.ElementTree as ET
from pathlib import Path
from xml.sax.saxutils import escape

R = Path(__file__).resolve().parents[2]
dump = Path(sys.argv[1] if len(sys.argv) > 1 else "/private/tmp/claude-501/hh_tests/settings_dump.json")
out = R / "Common/Languages/English/Keyed/HH_Settings.xml"
have = set()
for f in (R / "Common/Languages/English/Keyed").glob("*.xml"):
    if f == out: continue
    have |= {e.tag for e in ET.parse(f).getroot()}

def words(name):  # "WakeVolunteers" -> "Wake volunteers"
    s = re.sub(r"(?<=[a-z0-9])(?=[A-Z])", " ", name).strip()
    return s[:1].upper() + s[1:].lower() if s else name

entries = {}
for s in json.loads(dump.read_text(encoding="utf-8")):
    k = "HH.Setting." + s["key"]
    if s.get("label") and k not in have: entries[k] = s["label"]
    if s.get("desc") and k + ".Desc" not in have: entries[k + ".Desc"] = s["desc"]
    if s.get("category"):
        ck = "HH.SettingCat." + s["catKey"]
        if ck not in have: entries.setdefault(ck, s["category"])
    if s.get("enumType"):
        for n in s.get("enumNames") or []:
            ek = f"HH.Enum.{s['enumType']}.{n}"
            if ek not in have: entries.setdefault(ek, words(n))
lines = ['<?xml version="1.0" encoding="utf-8"?>', "<LanguageData>",
         "  <!-- Setting labels, descriptions, categories and choices (generated by tools/i18n/settings_keyed.py from the registered settings; English is the source) -->"]
lines += [f"  <{k}>{escape(v)}</{k}>" for k, v in sorted(entries.items())]
lines.append("</LanguageData>")
out.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(len(entries), "keys ->", out.relative_to(R))
