#!/usr/bin/env python3
"""Regenerates Common/Languages/English/Keyed/HH_Inn.xml from the English fallbacks in Source/Hearth/Guests
("HH.Inn.X".TranslateOr("text")), the settings registrations (HH.Setting.<key>[.Desc]) and a few computed keys.
Run: python3 tools/inn/gen_keyed.py"""
import re
from pathlib import Path
from xml.sax.saxutils import escape
R = Path(__file__).resolve().parents[2]
SRC = R / "Source" / "Hearth" / "Guests"
keys = {}
lit = r'"((?:[^"\\]|\\.)*)"'
for f in sorted(SRC.glob("*.cs")):
    if f.name == "InnTests.cs":
        continue
    t = f.read_text(encoding="utf-8")
    for m in re.finditer(r'"(HH\.[A-Za-z0-9_.]+)"\s*\.TranslateOr\(\s*' + lit, t):
        keys.setdefault(m.group(1), m.group(2))
    for m in re.finditer(r'\(\s*\w+\s*\?\s*"(HH\.[A-Za-z0-9_.]+)"\s*:\s*"(HH\.[A-Za-z0-9_.]+)"\s*\)\s*\.TranslateOr\(\s*\w+\s*\?\s*' + lit + r'\s*:\s*' + lit, t):
        keys.setdefault(m.group(1), m.group(3)); keys.setdefault(m.group(2), m.group(4))
# computed keys
reg = (SRC / "GuestRegistry.cs").read_text(encoding="utf-8")
vk = re.search(r'string\[\] verdict = \{([^}]*)\}', reg).group(1); vf = re.search(r'string\[\] fallback = \{([^}]*)\}', reg).group(1)
for k, v in zip(re.findall(lit, vk), re.findall(lit, vf)):
    keys.setdefault(k, v)
beds = (SRC / "GuestBeds.cs").read_text(encoding="utf-8")
for m in re.finditer(r'\("(\w+)", "([^"]+)", [\d.f]+, \d+, \d+, [\d.f]+\)', beds):
    keys.setdefault("HH.Inn.RoomClass." + m.group(1), m.group(2))
rep = (SRC / "DepartureReport.cs").read_text(encoding="utf-8")
for m in re.finditer(r'\["(\w+)"\] = new\[\]\s*\{(.*?)\},', rep, re.S):
    for i, s in enumerate(re.findall(lit, m.group(2))):
        keys.setdefault(f"HH.Inn.Report.Opener.{m.group(1)}.{i}", s)
# settings
st = (SRC / "InnSettings.cs").read_text(encoding="utf-8")
consts = dict(re.findall(r'public const string (\w+) = "([^"]+)";', st))
for m in re.finditer(r'HSettings\.\w+\(M, "[^"]+", (\w+),.*?' + lit + r',\s*' + lit, st, re.S):
    k = consts.get(m.group(1))
    if k:
        keys.setdefault("HH.Setting." + k, m.group(2)); keys.setdefault("HH.Setting." + k + ".Desc", m.group(3))
for n in ("Letter", "Message", "Off"):
    keys.setdefault("HH.Enum.InnReportMode." + n, {"Letter": "Letter", "Message": "Message", "Off": "Off"}[n])
out = R / "Common" / "Languages" / "English" / "Keyed" / "HH_Inn.xml"
out.parent.mkdir(parents=True, exist_ok=True)
lines = ['<?xml version="1.0" encoding="utf-8"?>', "<LanguageData>", "  <!-- Inn & Hotel module (generated by tools/inn/gen_keyed.py from the English fallbacks in code) -->"]
for k in sorted(keys):
    v = keys[k].replace('\\"', '"').replace("\\n", "\\n")
    lines.append(f"  <{k}>{escape(v)}</{k}>")
lines.append("</LanguageData>")
out.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(len(keys), "keys →", out.relative_to(R))
