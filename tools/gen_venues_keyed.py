#!/usr/bin/env python3
"""Regenerates Common/Languages/English/Keyed/HH_Venues.xml from the C# sources of the venues module:
every  "HH.Venue.X".TranslateOr("English")  call and every HSettings registration in VenueSettings.cs.
Run: python3 tools/gen_venues_keyed.py"""
import re
from pathlib import Path
from xml.sax.saxutils import escape
R = Path(__file__).resolve().parent.parent
src = R / "Source" / "Hearth" / "Venues"
entries = {}
lit = r'"((?:[^"\\]|\\.)*)"'
# 1.1.0: setup guide (HH.Setup), honor system (HH.Honor), serving (HH.Serve), names (HH.Names) and the work-side switch of Hearth.Core (HH.Core.Flip*)
files = sorted(src.glob("*.cs")) + [R / "Source" / "Hearth.Core" / "Foundation" / "CompFlipWorkSide.cs"]
for f in files:
    t = f.read_text(encoding="utf-8")
    for m in re.finditer(r'"(HH\.(?:Venue|Setup|Honor|Serve|Names|Core\.Flip)[A-Za-z0-9_.]*)"\s*\.TranslateOr\(\s*' + lit, t):
        entries.setdefault(m.group(1), m.group(2).replace('\\"', '"'))
# keys used without TranslateOr (ITab labelKey)
entries.setdefault("HH.Setup.TabLabel", "Setup")
# price tiers use computed keys
for tier, en in [("Free", "Free"), ("Charity", "Charity"), ("Discount", "Discount"), ("Budget", "Budget"), ("Standard", "Standard"), ("Premium", "Premium"), ("Luxury", "Luxury")]:
    entries.setdefault("HH.Venue.Tier." + tier, en)
# settings
# settings live in VenueSettings.cs and in NightBell.cs (NightBellSettings, 1.1.0)
st = (src / "VenueSettings.cs").read_text(encoding="utf-8") + "\n" + (src / "NightBell.cs").read_text(encoding="utf-8")
consts = dict(re.findall(r'public const string (\w+) = "([^"]+)";', st))
# keys defined in VenueSetup.cs and referenced from VenueSettings.cs (RequireSetup = VenueSetup.RequireKey)
setup_consts = dict(re.findall(r'public const string (\w+) = "([^"]+)";', (src / "VenueSetup.cs").read_text(encoding="utf-8")))
for name, ref in re.findall(r'public const string (\w+) = VenueSetup\.(\w+);', st):
    consts[name] = setup_consts[ref]
for m in re.finditer(r'HSettings\.(?:Float|Int|Percent|Silver|Bool|Enum(?:<\w+>)?)\(M, ("(?:[^"\\]|\\.)*"), (\w+),(.*?)\);', st, re.S):
    key = consts[m.group(2)]
    strs = re.findall(lit, m.group(3))
    # Enum registration: the 'def' argument is not a string, so the first two strings are label and description
    # others: numbers only before the label, so the first two strings are label and description as well
    label = strs[0]; desc = strs[1] if len(strs) > 1 else ""
    entries["HH.Setting." + key] = label
    if desc: entries["HH.Setting." + key + ".Desc"] = desc
# labels of the enum values shown in the settings dropdowns (HSettings looks up HH.Enum.<EnumType>.<Name>)
for k, en in [("BellWakes.Off", "Off (the bell only rings)"), ("BellWakes.AwakeOnly", "Awake colonists only"),
              ("BellWakes.WakeVolunteers", "Also wake volunteers"), ("BellWho.ServingOnly", "Serving colonists only"),
              ("BellWho.AnyColonist", "Any colonist")]:
    entries["HH.Enum." + k] = en
# keys that only appear as .Translate() in code (no English fallback to read) are kept from the existing file instead of being dropped
from xml.sax.saxutils import unescape
_old = R / "Common" / "Languages" / "English" / "Keyed" / "HH_Venues.xml"
if _old.exists():
    for m in re.finditer(r"^\s*<(HH\.[A-Za-z0-9_.]+)>(.*)</\1>\s*$", _old.read_text(encoding="utf-8"), re.M):
        entries.setdefault(m.group(1), unescape(m.group(2)))
out = ['<?xml version="1.0" encoding="utf-8"?>', "<LanguageData>", "  <!-- Venues, shops and staffing (generated by tools/gen_venues_keyed.py; edit the English in the C# source or here) -->"]
for k in sorted(entries):
    out.append(f"  <{k}>{escape(entries[k])}</{k}>")
out.append("</LanguageData>")
p = R / "Common" / "Languages" / "English" / "Keyed" / "HH_Venues.xml"
p.parent.mkdir(parents=True, exist_ok=True)
p.write_text("\n".join(out) + "\n", encoding="utf-8")
print(len(entries), "keys ->", p)
