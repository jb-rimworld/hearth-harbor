#!/usr/bin/env python3
"""Generates Common/Languages/English/Keyed/HH_Finance.xml from the E("key", "text") table in
Source/Silverline/Investments/FinanceText.cs (single source of the English finance texts).
Run: python3 tools/gen_finance_keyed.py"""
import re
from pathlib import Path
from xml.sax.saxutils import escape
R = Path(__file__).resolve().parent.parent
src = (R / "Source/Silverline/Investments/FinanceText.cs").read_text(encoding="utf-8")
items = re.findall(r'E\("([^"]+)",\s*"((?:[^"\\]|\\.)*)"\);', src)
def unescape(s): return s.replace('\\"', '"').replace('\\n', '\n').replace('\\\\', '\\')
out = ['<?xml version="1.0" encoding="utf-8"?>', '<LanguageData>', '  <!-- Generated by tools/gen_finance_keyed.py from FinanceText.cs. Edit the table in code, then regenerate. -->']
for k, v in items:
    out.append(f'  <{k}>{escape(unescape(v))}</{k}>')
out.append('</LanguageData>')
p = R / "Common/Languages/English/Keyed/HH_Finance.xml"
p.parent.mkdir(parents=True, exist_ok=True)
p.write_text("\n".join(out) + "\n", encoding="utf-8")
print(f"{len(items)} keys -> {p.relative_to(R)}")
