#!/usr/bin/env python3
"""Generates Common/Languages/English/Keyed/HH_Bank.xml from every L.T("Key", "English text") literal in Source/Silverline.
Run: python3 tools/gen_bank_keys.py   (keys become HH.Bank.<Key>; the C# fallback and the Keyed file can never drift)."""
import re, sys
from pathlib import Path
from xml.sax.saxutils import escape
R = Path(__file__).resolve().parent.parent
pat = re.compile(r'L\.T\(\s*"((?:[^"\\]|\\.)*)"\s*,\s*"((?:[^"\\]|\\.)*)"')
keys = {}
for f in sorted((R / "Source" / "Silverline").rglob("*.cs")):
    if f.name == "L.cs": continue
    t = f.read_text(encoding="utf-8")
    for m in pat.finditer(t):
        k = m.group(1)
        v = bytes(m.group(2), "utf-8").decode("unicode_escape").encode("latin-1", "ignore").decode("utf-8", "ignore") if "\\" in m.group(2) else m.group(2)
        v = m.group(2).replace('\\n', '\n').replace('\\"', '"').replace('\\\\', '\\')
        if k in keys and keys[k] != v: print("WARNING duplicate key with different text:", k, file=sys.stderr)
        keys.setdefault(k, v)
# tab labels use LabelKey = "HH.Bank.Tab.X"
for k, v in {"Tab.Lobby": "Lobby", "Tab.Loans": "Loans", "Tab.History": "History", "Tab.Terms": "Terms"}.items(): keys.setdefault(k, v)
for i, n in enumerate(["Drowning in Debt", "Broke", "Scraping By", "Getting By", "Comfortable", "Well-Off", "Rich", "Filthy Rich", "Too Big To Fail"]): keys.setdefault(f"Tier.{i}", n)
for i, n in enumerate(["Comped", "All-Inclusive", "Bed & Breakfast", "Standard Room", "Overbooked", "One-Star Review", "Why are you hurting yourself?"]): keys.setdefault(f"Tier.Name{i}", n)
out = ['<?xml version="1.0" encoding="utf-8"?>', "<LanguageData>", "  <!-- generated by tools/gen_bank_keys.py from the L.T(...) calls in Source/Silverline; do not edit by hand -->"]
for k in sorted(keys):
    out.append(f"  <HH.Bank.{k}>{escape(keys[k])}</HH.Bank.{k}>")
out.append("</LanguageData>")
p = R / "Common" / "Languages" / "English" / "Keyed" / "HH_Bank.xml"
p.parent.mkdir(parents=True, exist_ok=True)
p.write_text("\n".join(out) + "\n", encoding="utf-8")
print(f"{len(keys)} keys -> {p.relative_to(R)}")
